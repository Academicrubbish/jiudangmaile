function choices(event) {
  const key =
    event.kind === 'treat'
      ? 'treat'
      : LIBRARY[event.habit]
        ? event.habit
        : 'custom';
  const name = ITEMS[event.habit]?.name || event.item;
  return LIBRARY[key].map(([motif, title, body, summary]) => ({
    title,
    body: body.replaceAll('{item}', name),
    summary,
    action_label: event.kind === 'treat' ? '这份我来请' : '这份算我买了',
    amount_cents: event.amount,
    motif: 'library_' + motif
  }));
}

function choose(event, recent = [], similar = () => false) {
  const pool = choices(event);
  // Least recently used selection also works when the finite library is exhausted.
  const lastUse = (candidate) => {
    let last = -1;
    recent.forEach((row, index) => {
      if (
        row.motif === candidate.motif ||
        row.body === candidate.body ||
        similar(
          (row.body || '').split(row.item || event.item).join('商品'),
          candidate.body
            .split(ITEMS[event.habit]?.name || event.item)
            .join('商品')
        )
      )
        last = index;
    });
    return last;
  };
  const oldest = Math.min(...pool.map(lastUse));
  const available = pool.filter((row) => lastUse(row) === oldest);
  const seed = parseInt(
    crypto.createHash('sha256').update(event.id).digest('hex').slice(0, 8),
    16
  );
  return available[seed % available.length];
}

module.exports = { choices, choose };
